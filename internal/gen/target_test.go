package gen_test

import (
	"slices"
	"strings"
	"testing"

	"github.com/go-kanna/internal/packages"
	"github.com/go-kanna/internal/pkgtest"

	"github.com/go-kanna/validate/internal/gen"
)

// targets loads files as one package and finds its targets, as gen.Targets
// spells them.
func targets(t *testing.T, files map[string]string) ([]string, []string) {
	t.Helper()

	pkg := pkgtest.Load(t, files)
	return gen.Targets(pkg.Fset, []*packages.Package{pkg})
}

func TestTargets(t *testing.T) {
	t.Parallel()

	names, diags := targets(t, map[string]string{
		"model.go": `package test

//kanna:validate
type Marked struct {
	Name string ` + "`validate:\"required\"`" + `
}

//kanna:validate
type Regenerated struct{}

type Plain struct {
	Name string ` + "`json:\"name\"`" + `
}
`,
		// What an earlier run left behind, which the next run replaces.
		"validate_gen.go": `// Code generated by kanna-validate. DO NOT EDIT.

package test

func (x Regenerated) Validate() error { return nil }
`,
	})

	if want := []string{"Marked", "Regenerated"}; !slices.Equal(names, want) {
		t.Errorf("targets = %q, want %q", names, want)
	}
	if len(diags) > 0 {
		t.Errorf("diagnostics = %q, want none", diags)
	}
}

func TestTargets_Hooks(t *testing.T) {
	t.Parallel()

	set, err := packages.Load([]string{"./testdata/hook"}, packages.Config{})
	if err != nil || len(set.Diags) > 0 {
		t.Fatalf("load: %v %v", err, set.Diags)
	}

	names, diags := gen.Targets(set.Fset, set.Packages)
	if want := []string{"Signup (hook)", "Audit (hook)", "Order"}; !slices.Equal(names, want) {
		t.Errorf("targets = %q, want %q", names, want)
	}
	if len(diags) > 0 {
		t.Errorf("diagnostics = %q, want none", diags)
	}
}

func TestTargets_Diagnostics(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  string
		want string
	}{
		{
			name: "tags without the directive",
			src: `package test

type Forgotten struct {
	Name string ` + "`validate:\"required\"`" + `
}
`,
			want: "test.go:3:6: warning: Forgotten has validate tags but no //kanna:validate, so they are never checked",
		},
		{
			name: "a broken tag without the directive",
			src: `package test

type Forgotten struct {
	Zip string ` + "`validate:\"\\d\"`" + `
}
`,
			want: "test.go:3:6: warning: Forgotten has validate tags but no //kanna:validate",
		},
		{
			name: "misspelled directive",
			src: `package test

//kanna:validte
type Misspelled struct{}
`,
			want: `did you mean "//kanna:validate"?`,
		},
		{
			name: "arguments",
			src: `package test

//kanna:validate strict
type WithArgs struct{}
`,
			want: `test.go:3:1: error: //kanna:validate takes no arguments, got "strict"`,
		},
		{
			name: "generic",
			src: `package test

//kanna:validate
type Box[T any] struct{ V T }
`,
			want: "test.go:4:6: error: generic struct Box is not supported",
		},
		{
			name: "field named Validate",
			src: `package test

//kanna:validate
type Clash struct {
	Validate bool
}
`,
			want: "test.go:5:2: error: Clash has a field named Validate, which the generated method would collide with",
		},
		{
			name: "hand-written Validate",
			src: `package test

//kanna:validate
type Manual struct{}

func (Manual) Validate() error { return nil }
`,
			want: "test.go:6:15: error: Manual already has a Validate method\n  remove it, or the //kanna:validate on Manual",
		},
		{
			name: "hook without a parameter",
			src: `package test

//kanna:validate
type Target struct{}

func (Target) validate() error { return nil }
`,
			want: "test.go:6:15: error: Target.validate must be func(*validate.Errors) for the generated Validate to call it\n" +
				"  rename it if it is not meant to be called from Validate",
		},
		{
			name: "hook taking a value",
			src: `package test

//kanna:validate
type Target struct{}

func (Target) validate(int) {}
`,
			want: "test.go:6:15: error: Target.validate must be func(*validate.Errors)",
		},
		{
			name: "hook taking another pointer",
			src: `package test

//kanna:validate
type Target struct{}

func (*Target) validate(*int) {}
`,
			want: "test.go:6:16: error: Target.validate must be func(*validate.Errors)",
		},
		{
			name: "hook taking Errors of another package",
			src: `package test

type Errors []error

//kanna:validate
type Target struct{}

func (Target) validate(*Errors) {}
`,
			want: "test.go:8:15: error: Target.validate must be func(*validate.Errors)",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			names, diags := targets(t, map[string]string{"test.go": tt.src})
			if len(names) > 0 {
				t.Errorf("targets = %q, want none", names)
			}
			if !slices.ContainsFunc(diags, func(d string) bool { return strings.Contains(d, tt.want) }) {
				t.Errorf("diagnostics = %q, want one containing %q", diags, tt.want)
			}
		})
	}
}
